// vendor-foundry-vocab.mjs: writes js/foundry-vocab.js, the words the Foundry
// export is allowed to put in a field.
//
//   node Pathfinder/converter-assets/vendor-foundry-vocab.mjs      (from the repo root)
//
// Reads Pathfinder/data/npcs/*.json (never writes them): the site's copy of
// the Foundry pf2e system's own NPC actors. Every trait, language, sense,
// immunity, weakness and resistance slug a Remaster NPC there carries goes
// into one sorted list each. js/foundry.js writes a slug into a field only if
// it is on its list, and puts the rest into the actor's notes as text, so the
// export never invents a slug. Run it when converter-foundry.test.mjs says
// foundry-vocab.js no longer matches the Archive.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, 'js', 'foundry-vocab.js');

export function buildVocab(npcDir = path.join(HERE, '..', 'data', 'npcs')) {
  const sets = { traits: new Set(), languages: new Set(), senses: new Set(), immunities: new Set(),
    weaknesses: new Set(), resistances: new Set(), exceptions: new Set(), actionTraits: new Set() };
  let actors = 0;
  for (const f of fs.readdirSync(npcDir).sort()) {
    for (const a of JSON.parse(fs.readFileSync(path.join(npcDir, f), 'utf8'))) {
      const sy = a.system;
      if (!sy.details?.publication?.remaster) continue;
      actors++;
      for (const t of sy.traits?.value || []) sets.traits.add(t);
      for (const l of sy.details?.languages?.value || []) sets.languages.add(l);
      for (const s of sy.perception?.senses || []) sets.senses.add(s.type);
      for (const i of sy.attributes?.immunities || []) sets.immunities.add(i.type);
      for (const w of sy.attributes?.weaknesses || []) sets.weaknesses.add(w.type);
      for (const r of sy.attributes?.resistances || []) {
        sets.resistances.add(r.type);
        for (const e of r.exceptions || []) if (typeof e === 'string') sets.exceptions.add(e);
      }
      for (const it of a.items || []) {
        if (it.type === 'action') for (const t of it.system?.traits?.value || []) sets.actionTraits.add(t);
      }
    }
  }
  const lists = Object.fromEntries(Object.entries(sets).map(([k, s]) => [k, [...s].filter((x) => typeof x === 'string' && x).sort()]));
  return { actors, lists };
}

export function vocabSource({ actors, lists }) {
  const body = Object.entries(lists).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n');
  return `// foundry-vocab.js: generated by ../vendor-foundry-vocab.mjs from the ${actors.toLocaleString('en-US')} Remaster
// NPCs in Pathfinder/data/npcs. Do not edit by hand; rerun the script.
export const VOCAB = {
${body}
};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const v = buildVocab();
  fs.writeFileSync(OUT, vocabSource(v));
  console.log(`foundry-vocab.js: ${Object.entries(v.lists).map(([k, l]) => `${l.length} ${k}`).join(', ')} from ${v.actors} actors`);
}
