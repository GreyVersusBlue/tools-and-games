// sync-social-tags.mjs — give every page linked from the board a favicon and a
// social preview, with the copy taken from that page's own notice on the board.
//
//   npm run social           # write the blocks
//   npm run social:check     # report drift, exit non-zero, write nothing
//
// WHY GENERATED RATHER THAN HAND-WRITTEN: the board already carries a title and a
// one-line description for all 24 pages, written in the site's voice
// (`<h3>` + `<p class="desc">` inside each `<a class="notice">`). Hand-copying
// that into 24 heads means 24 places for it to go stale the next time a notice
// gets reworded. This reads index.html as the single source and rewrites the
// blocks between the `gvb:social` markers, so a notice edit plus `npm run social`
// keeps board and share-card identical by construction.
//
// The FAVICON is deliberately the same mark on every page, not a per-project one:
// it is the site's seal, it is an inline SVG data-URI so it costs no request and
// no file, and a visitor moving from the board into a quest should see the tab
// icon stay put. (The phantom /favicon.ico 404 in every verification log since
// session 1 was just Chrome falling back to the origin root on pages that
// declared no icon.)
//
// The OG IMAGE is per-project where one exists. og:image wants ~1200x630;
// the 330x200 hover previews are far too small for a share card, so
// promote-previews.mjs writes both sizes from the same chosen frame and this
// points at assets/og/<slug>.jpg. Pages with no capture get the board's own
// guild-board.png.

import fs from 'node:fs';
import path from 'node:path';
import { SITE } from './harness.mjs';

const ORIGIN = 'https://greyversusblue.com';
const START = '<!-- gvb:social:start — generated by Tools/board-check/sync-social-tags.mjs; edit the notice in index.html, not this -->';
const END = '<!-- gvb:social:end -->';

// Same data-URI as index.html and 404.html.
const ICON = "data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'%3E%3Crect width='32' height='32' fill='%233B2A1A'/%3E%3Ccircle cx='16' cy='16' r='10' fill='%237E2A20'/%3E%3Ccircle cx='13' cy='13' r='3.5' fill='%23A8443A'/%3E%3C/svg%3E";

const check = process.argv.includes('--check');

/* ------------------------------------------------- read the board's notices -- */

const boardHtml = fs.readFileSync(path.join(SITE, 'index.html'), 'utf8');

const notices = [];
const anchorRe = /<a class="notice[^"]*"([^>]*)>([\s\S]*?)<\/a>/g;
for (const m of boardHtml.matchAll(anchorRe)) {
  const attrs = m[1], body = m[2];
  const href = attrs.match(/href="([^"]+)"/)?.[1];
  const title = body.match(/<h3>([\s\S]*?)<\/h3>/)?.[1]?.trim();
  const desc = body.match(/<p class="desc">([\s\S]*?)<\/p>/)?.[1]?.trim();
  const preview = attrs.match(/data-preview="assets\/previews\/([^".]+)\.jpg"/)?.[1];
  if (!href || !title || !desc) continue;
  notices.push({ href, title, desc, preview });
}

// The board dropped from 22 notices to 17 this round: the six standalone Tools
// notices were replaced by one "School Tools" card pointing at newindex.html.
// That is a real, deliberate count, not a parse failure — confirmed by reading
// every one of the 17 anchors back with title/desc/href intact. The floor below
// is a sanity check against a markup change silently dropping notices, not
// against this file knowing the exact count; keep the same two-notice buffer
// round 1 used (22 - 2 = 20) rather than pinning to a number that will need
// editing again next time a section's shape changes on purpose.
if (notices.length < 15) {
  console.error(`only parsed ${notices.length} notices out of index.html — the notice markup has changed shape, fix the regexes rather than shipping a partial sweep`);
  process.exit(2);
}

/* ------------------------------------------------------------- build blocks -- */

// The board's copy is already HTML-escaped for a text node; a double-quoted
// attribute additionally needs its quotes handled. Nothing in the current copy
// contains one, but "&#39;" appearing where an apostrophe belongs would be a
// silent wrong-looking share card, so unescape to text and re-escape for an
// attribute rather than passing it through.
const toText = s => s
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'");
const attr = s => toText(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** '/Projects/Closing Time/' -> the file that actually serves it. */
function fileFor(href) {
  const rel = decodeURIComponent(href);
  const abs = path.join(SITE, rel);
  if (rel.endsWith('/')) return path.join(abs, 'index.html');
  return abs;
}

function blockFor(n) {
  const url = `${ORIGIN}/${n.href.replace(/ /g, '%20')}`;
  const img = n.preview
    ? `${ORIGIN}/assets/og/${n.preview}.jpg`
    : `${ORIGIN}/assets/og/guild-board.png`;
  const title = `${attr(n.title)} — greyversusblue`;
  const desc = attr(n.desc);
  const alt = n.preview
    ? `${attr(n.title)}, mid-play.`
    : `A tavern notice board headed 'The Guild Board of greyversusblue'.`;
  return [
    START,
    `<meta name="description" content="${desc}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="greyversusblue">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:title" content="${title}">`,
    `<meta property="og:description" content="${desc}">`,
    `<meta property="og:image" content="${img}">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    `<meta property="og:image:alt" content="${alt}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${title}">`,
    `<meta name="twitter:description" content="${desc}">`,
    `<meta name="twitter:image" content="${img}">`,
    `<link rel="icon" href="${ICON}">`,
    END,
  ].join('\n');
}

/* ------------------------------------------------------------------- apply -- */

let wrote = 0, same = 0, stale = 0, missing = 0, failed = 0;

for (const n of notices) {
  const file = fileFor(n.href);
  const label = path.relative(SITE, file).replace(/\\/g, '/');

  if (!fs.existsSync(file)) {
    failed++; console.log(`  FAIL  ${label}  linked from the board but not on disk`);
    continue;
  }

  const src = fs.readFileSync(file, 'utf8');
  const block = blockFor(n);
  let out;

  const s = src.indexOf(START);
  if (s !== -1) {
    const e = src.indexOf(END, s);
    if (e === -1) { failed++; console.log(`  FAIL  ${label}  unterminated gvb:social block`); continue; }
    out = src.slice(0, s) + block + src.slice(e + END.length);
    if (out === src) { same++; continue; }
    stale++;
  } else {
    // First insertion goes straight after </title>, which every page has and
    // which is above anything that could depend on it.
    const t = src.search(/<\/title>\s*\n?/i);
    if (t === -1) { failed++; console.log(`  FAIL  ${label}  no <title> to anchor the block to`); continue; }
    const after = src.indexOf('\n', t) + 1;
    // An already-hand-written icon or og tag would end up duplicated. Say so
    // rather than quietly emitting two of each.
    if (/rel="icon"|property="og:/.test(src)) {
      failed++;
      console.log(`  FAIL  ${label}  already has hand-written icon/og tags — remove them first`);
      continue;
    }
    out = src.slice(0, after) + block + '\n' + src.slice(after);
    missing++;
  }

  if (!check) fs.writeFileSync(file, out);
  console.log(`  ${check ? 'DRIFT' : 'ok   '}  ${label}`);
}

console.log(`\n${notices.length} notices · ${same} already current · ` +
  `${missing} had no block · ${stale} out of date · ${failed} failed`);
if (check) {
  const drift = missing + stale + failed;
  console.log(drift
    ? `${drift} page(s) out of sync with the board — run \`npm run social\``
    : 'every page is in sync with the board');
  process.exit(drift ? 1 : 0);
}
console.log(failed ? `${failed} page(s) need a human` : 'all pages written');
process.exit(failed ? 1 : 0);
